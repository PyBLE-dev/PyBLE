import {
  cp,
  copyFile,
  lstat,
  mkdir,
  readFile,
  rename,
  stat,
  writeFile,
} from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import {
  validateFreshDeploymentBundle,
  validateStagedFirmwareRelease,
} from "./stage-firmware-release.js";

/** @typedef {{ route?: string, status?: string }} PrerenderRoute */

/**
 * @param {string} path
 * @param {string} missingMessage
 * @returns {Promise<void>}
 */
async function requireFile(path, missingMessage) {
  try {
    const file = await stat(path);
    if (!file.isFile()) {
      throw new Error(missingMessage);
    }
  } catch (error) {
    if (error instanceof Error && "code" in error && error.code === "ENOENT") {
      throw new Error(missingMessage, { cause: error });
    }
    throw error;
  }
}

const requiredPrerenderedRoutes = [
  "/",
  "/flash",
  "/privacy",
  "/support",
  "/404",
];

/**
 * @param {string} notFoundHtml
 * @returns {string}
 */
function createSitesEntrypoint(notFoundHtml) {
  const serializedNotFoundHtml = JSON.stringify(notFoundHtml)
    .replaceAll("\u2028", "\\u2028")
    .replaceAll("\u2029", "\\u2029");

  return `// Generated by scripts/prepare-sites-output.js.
import vinextHandler from "./vinext-handler.js";

const delegatedPaths = new Set([
  "/",
  "/privacy",
  "/privacy/",
  "/support",
  "/support/",
  "/flash",
  "/flash/",
  "/robots.txt",
  "/sitemap.xml",
  "/manifest.webmanifest",
]);
const notFoundHtml = ${serializedNotFoundHtml};

function delegatesToVinext(pathname) {
  return (
    delegatedPaths.has(pathname) ||
    pathname.startsWith("/_next/") ||
    pathname.startsWith("/app/") ||
    pathname.startsWith("/brand/") ||
    pathname.startsWith("/firmware/")
  );
}

function pybleSitesHandler(request, context) {
  const pathname = new URL(request.url).pathname;
  if (delegatesToVinext(pathname)) {
    return vinextHandler(request, context);
  }

  return new Response(request.method === "HEAD" ? null : notFoundHtml, {
    status: 404,
    headers: {
      "Cache-Control": "public, max-age=0, must-revalidate",
      "Content-Type": "text/html; charset=utf-8",
      "X-Content-Type-Options": "nosniff",
    },
  });
}

export default {
  fetch(request, _environment, context) {
    return pybleSitesHandler(request, context);
  },
};
`;
}

/**
 * @param {string} manifestPath
 * @returns {Promise<void>}
 */
async function requirePrerenderedRoutes(manifestPath) {
  /** @type {{ routes?: PrerenderRoute[] }} */
  let manifest;
  try {
    manifest = JSON.parse(await readFile(manifestPath, "utf8"));
  } catch (error) {
    throw new Error(`Vinext prerender manifest is invalid: ${manifestPath}`, {
      cause: error,
    });
  }

  const routeStatuses = new Map(
    Array.isArray(manifest.routes)
      ? manifest.routes.map((entry) => [entry.route, entry.status])
      : [],
  );

  for (const route of requiredPrerenderedRoutes) {
    if (routeStatuses.get(route) !== "rendered") {
      throw new Error(`Launch route was not prerendered: ${route}`);
    }
  }
}

/**
 * Finalize the complete vinext bundle for Sites without replacing any of its
 * client, server, or hidden build artifacts.
 *
 * @param {string} packageRoot
 * @param {string | undefined} stagedFirmwareRoot
 * @param {(bundleDirectory: string, deployment: "public" | "candidate" | "public-beta") => Promise<void>} releaseValidator
 * @returns {Promise<void>}
 */
export async function prepareSitesOutput(
  packageRoot,
  stagedFirmwareRoot = process.env.PYBLE_FIRMWARE_STAGED_ROOT,
  releaseValidator = validateFreshDeploymentBundle,
) {
  const selectionFile = process.env.PYBLE_FLASH_SELECTION_FILE;
  if (Boolean(stagedFirmwareRoot) !== Boolean(selectionFile)) {
    throw new Error(
      "Sites firmware staging requires both PYBLE_FIRMWARE_STAGED_ROOT and PYBLE_FLASH_SELECTION_FILE",
    );
  }
  if (
    stagedFirmwareRoot &&
    selectionFile &&
    resolve(selectionFile) !==
      join(
        resolve(stagedFirmwareRoot),
        ".pyble-firmware-release-selection.json",
      )
  ) {
    throw new Error(
      "Sites firmware selector must be the exact descriptor inside the staged root",
    );
  }

  const serverEntrypoint = join(packageRoot, "dist", "server", "index.js");
  const vinextEntrypoint = join(
    packageRoot,
    "dist",
    "server",
    "vinext-handler.js",
  );
  const prerenderManifest = join(
    packageRoot,
    "dist",
    "server",
    "vinext-prerender.json",
  );
  const sourceBinding = join(packageRoot, ".openai", "hosting.json");
  const targetBinding = join(packageRoot, "dist", ".openai", "hosting.json");
  const notFoundDocument = join(packageRoot, "dist", "client", "404.html");

  await requireFile(
    serverEntrypoint,
    `Vinext server entrypoint is missing: ${serverEntrypoint}`,
  );
  await requireFile(
    sourceBinding,
    `Sites project binding is missing: ${sourceBinding}`,
  );
  await requireFile(
    prerenderManifest,
    `Vinext prerender manifest is missing: ${prerenderManifest}`,
  );
  await requirePrerenderedRoutes(prerenderManifest);

  const requiredArtifactFiles = [
    join(packageRoot, "dist", "server", "ssr", "index.js"),
    join(packageRoot, "dist", "client", ".vite", "manifest.json"),
    notFoundDocument,
    join(packageRoot, "dist", "client", "robots.txt"),
    join(packageRoot, "dist", "client", "sitemap.xml"),
    join(packageRoot, "dist", "client", "manifest.webmanifest"),
  ];
  await Promise.all(
    requiredArtifactFiles.map((path) =>
      requireFile(path, `Required Sites artifact is missing: ${path}`),
    ),
  );

  if (stagedFirmwareRoot) {
    await validateStagedFirmwareRelease(stagedFirmwareRoot, {
      releaseValidator,
    });
    const firmwareTarget = join(packageRoot, "dist", "client", "firmware");
    try {
      await lstat(firmwareTarget);
      throw new Error(
        `Sites firmware target already exists: ${firmwareTarget}`,
      );
    } catch (error) {
      if (
        !(error instanceof Error) ||
        !("code" in error) ||
        error.code !== "ENOENT"
      ) {
        throw error;
      }
    }
    await cp(join(resolve(stagedFirmwareRoot), "firmware"), firmwareTarget, {
      recursive: true,
      errorOnExist: true,
      force: false,
    });
  }

  const notFoundHtml = await readFile(notFoundDocument, "utf8");
  await rename(serverEntrypoint, vinextEntrypoint);
  await writeFile(
    serverEntrypoint,
    createSitesEntrypoint(notFoundHtml),
    "utf8",
  );

  await mkdir(dirname(targetBinding), { recursive: true });
  await copyFile(sourceBinding, targetBinding);
}

const invokedPath = process.argv[1];
if (
  invokedPath &&
  import.meta.url === pathToFileURL(resolve(invokedPath)).href
) {
  const packageRoot = fileURLToPath(new URL("..", import.meta.url));
  prepareSitesOutput(packageRoot).catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  });
}
